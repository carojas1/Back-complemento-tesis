// Spec 113 FR-011: images up to 1 MB and 4096 px per side, verified by their bytes (OWASP File Upload Cheat Sheet,
// ASVS 5.2.1, 5.2.2 and 5.2.6). The app shrinks them before uploading; the server does not rely on that.
import { Role } from '../src/auth/domain/entities/user.entity';
import { createTestApp, png, TestApp } from './app';

let t: TestApp;
let admin: string;
let ana: string;
let anaId: string;

// PNG with the header of a `side` × `side` px image (weighs few bytes: the «pixel bomb» attack).
const pngOf = (side: number) => {
  const head = Buffer.from(png);
  head.writeUInt32BE(side, 16);
  head.writeUInt32BE(side, 20);
  return head;
};
// Minimal JPEG with an APP0 marker and the SOF0 that states its size.
const jpegOf = (side: number) => {
  const app0 = [0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00];
  const sof0 = [0xff, 0xc0, 0x00, 0x11, 0x08, side >> 8, side & 0xff, side >> 8, side & 0xff, 0x03, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1];
  return Buffer.from([0xff, 0xd8, ...app0, ...sof0, 0xff, 0xd9]);
};
const svg = (body: string) => Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10">${body}</svg>`);
const pictogram = (image: Buffer, name = 'p.png') =>
  t.http().post('/pictograms').auth(ana, { type: 'bearer' }).field('label', 'prueba').attach('image', image, name);
const avatar = (image: Buffer, name = 'a.svg') =>
  t.http().post('/catalogs/avatars').auth(admin, { type: 'bearer' }).field('name', `a-${crypto.randomUUID()}`).attach('image', image, name);

beforeAll(async () => {
  t = await createTestApp();
  await t.reset();
  await t.createUser('jefe@centro.org', Role.ADMIN);
  anaId = (await t.createUser('ana@centro.org')).id;
  admin = (await t.login('jefe@centro.org')).token;
  ana = (await t.login('ana@centro.org')).token;
});
afterAll(() => t.app.close());

describe('pictogramas propios', () => {
  it('accepts small PNG and JPEG, verified by their bytes', async () => {
    expect((await pictogram(png)).status).toBe(201);
    expect((await pictogram(jpegOf(512), 'p.jpg')).status).toBe(201);
    expect((await pictogram(pngOf(4096))).status).toBe(201);
  });

  it('over 1 MB: 413, saving nothing', async () => {
    const before = await t.prisma.pictogram.count();
    expect((await pictogram(Buffer.concat([png, Buffer.alloc(1_000_001)]))).status).toBe(413);
    expect(await t.prisma.pictogram.count()).toBe(before);
  });

  it('over 4096 px per side, or bytes that are not an image: 400 InvalidImage', async () => {
    for (const image of [
      pngOf(4097),
      pngOf(50_000),
      jpegOf(5000),
      Buffer.from('<?php system($_GET["c"]); ?>'),
      Buffer.from('GIF89a'),
      png.subarray(0, 12),
    ])
      expect((await pictogram(image)).body).toMatchObject({ statusCode: 400, error: 'InvalidImage' });
  });

  it('the name and the mimetype sent by the client do not count', async () => {
    const res = await t
      .http()
      .post('/pictograms')
      .auth(ana, { type: 'bearer' })
      .field('label', 'x')
      .attach('image', png, { filename: '../../etc/passwd', contentType: 'text/html' });
    expect(res.status).toBe(201);
    const saved = await t.prisma.pictogram.findUniqueOrThrow({ where: { id: res.body.id } });
    expect(saved.imagePath).toMatch(/^pictograms\/uploads\/[0-9a-f-]+\.png$/); // path generated by the API
  });
});

describe('avatares', () => {
  it('SVG limpio, PNG o JPEG hasta 200 KB', async () => {
    expect((await avatar(svg('<circle r="4"/>'))).status).toBe(201);
    expect((await avatar(png, 'a.png')).status).toBe(201);
  });

  it('SVG with scripts or event handlers: 400', async () => {
    for (const body of [
      '<script>alert(1)</script>',
      '<rect onload="alert(1)"/>',
      '<a href="javascript:alert(1)"><rect/></a>',
      '<foreignObject><p/></foreignObject>',
    ])
      expect([body, (await avatar(svg(body))).status]).toEqual([body, 400]);
  });

  it('a pixel bomb: 400', async () => {
    expect((await avatar(pngOf(20_000), 'a.png')).status).toBe(400);
  });
});

describe('patient consent', () => {
  const register = async (image: Buffer) => {
    const avatarId = (await avatar(svg('<rect/>'))).body.id as string;
    let req = t.http().post('/patients').auth(admin, { type: 'bearer' });
    const fields = { firstNames: 'Mateo', lastNames: 'Pérez', birthDate: '2018-05-20', guardianName: 'Lucía', guardianPhone: '0991234567' };
    for (const [key, value] of Object.entries({ ...fields, consentDate: '2026-10-20', avatarId, therapistIds: anaId }))
      req = req.field(key, value);
    return req.attach('consentImage', image, 'c.jpg');
  };

  it('up to 1 MB and 4096 px; larger is rejected and the patient is not registered', async () => {
    expect((await register(jpegOf(2000))).status).toBe(201);
    expect((await register(Buffer.concat([jpegOf(2000), Buffer.alloc(1_000_001)]))).status).toBe(413);
    expect((await register(jpegOf(8000))).body).toMatchObject({ statusCode: 400, error: 'ConsentRequired' });
    expect(await t.prisma.patient.count()).toBe(1);
  });
});

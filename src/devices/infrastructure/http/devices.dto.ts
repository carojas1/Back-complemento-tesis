import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Transform } from 'class-transformer';
import { IsOptional, IsString, Length, Matches, MaxLength } from 'class-validator';
import { pinPattern } from '../../../auth/domain/entities/user.entity';
import { trim } from '../../../common/validation/trim';

// Spec 103 FR-007: generating a code requires the current Center PIN (security).
export class CreateRegistrationCodeDto {
  @ApiProperty({ example: '2580', description: '4 to 6 digits, no sequences like 1111 or 1234' })
  @IsString({ message: 'Ingrese el PIN del Centro' })
  @Matches(pinPattern, { message: 'El PIN del Centro debe tener de 4 a 6 dígitos' })
  centerPin: string;
}

export class RegisterDeviceDto {
  @ApiProperty({ example: 'K7PX3MQA', description: '8-character code generated by the admin' })
  @IsString({ message: 'Ingrese el código' })
  @MaxLength(32, { message: 'Código no válido o vencido' })
  code: string;

  @ApiProperty({ example: 'Tableta Sala 1' })
  @Transform(trim)
  @IsString({ message: 'Ingrese un nombre para la tableta' })
  @Length(1, 60, { message: 'El nombre debe tener entre 1 y 60 caracteres' })
  name: string;

  @ApiPropertyOptional({ example: 'SM-T225' })
  @IsOptional()
  @IsString()
  @MaxLength(100)
  model?: string;

  @ApiPropertyOptional({ example: '1.0.0' })
  @IsOptional()
  @IsString()
  @MaxLength(30)
  appVersion?: string;

  @ApiProperty({ description: 'ECDSA P-256 public key from the Keystore, SPKI in base64' })
  @IsString({ message: 'Falta la llave pública' })
  @MaxLength(500)
  publicKey: string;
}

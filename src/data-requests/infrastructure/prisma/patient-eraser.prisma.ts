import { Injectable } from '@nestjs/common';
import { PrismaService } from '../../../prisma/prisma.service';
import { currentInstitution } from '../../../tenancy/tenancy';
import { anonymousPatientCode, DataRequest } from '../../domain/entities/data-request.entity';
import { PatientEraser } from '../../domain/ports/data-requests.repository';
import { nextSyncVersion } from '../../../prisma/sync-version';

@Injectable()
export class PatientEraserPrisma extends PatientEraser {
  constructor(private readonly prisma: PrismaService) {
    super();
  }

  // All or nothing. Deleting the Patient cascades (onDelete: Cascade) to assignments, conditions, profile with its board and
  // recordings, voice with its audios, observations and goals. Sessions have no cascade: they are moved or deleted first.
  // Queue jobs (no FK) are deleted by hand along with their files.
  async erase({
    patientId,
    anonymize,
    adminId,
    request,
  }: {
    patientId: string;
    anonymize: boolean;
    adminId: string;
    request: DataRequest;
  }) {
    return this.prisma.$transaction(
      async (tx) => {
        const patient = await tx.patient.findUniqueOrThrow({
          where: { id: patientId },
          select: {
            code: true,
            avatarId: true,
            consentFilePath: true,
            profile: { select: { pictograms: { where: { recordingPath: { not: null } }, select: { recordingPath: true } } } },
            voice: { select: { samplePath: true, clips: { select: { path: true } } } },
          },
        });
        const files = [
          patient.consentFilePath,
          ...(patient.profile?.pictograms.map((p) => p.recordingPath!) ?? []),
          ...(patient.voice ? [patient.voice.samplePath, ...patient.voice.clips.map((c) => c.path)] : []),
        ].filter(Boolean);

        // PDFs and ZIPs generated by the queue (jobs module): patient data that is also deleted from the bucket.
        const jobs = await tx.job.findMany({ where: { patientId }, select: { resultPath: true } });
        await tx.job.deleteMany({ where: { patientId } });
        files.push(...jobs.flatMap((job) => (job.resultPath ? [job.resultPath] : [])));

        let sessions: number;
        if (anonymize) {
          // Technical patient with nobody's data: discharged since 1970, not downloaded to tablets and accepts no new sessions.
          const anonymous = await tx.patient.upsert({
            where: { institutionId_code: { institutionId: currentInstitution(), code: anonymousPatientCode } },
            update: {},
            create: {
              code: anonymousPatientCode,
              avatarId: patient.avatarId,
              firstNames: 'Anónimo',
              lastNames: 'Anónimo',
              birthDate: new Date('1900-01-01'),
              guardianName: '-',
              guardianPhone: '-',
              consentDate: new Date('1900-01-01'),
              consentFilePath: '',
              status: 'DISCHARGED',
              dischargedAt: new Date(0),
              createdBy: adminId,
            },
            select: { id: true },
          });
          // The therapist is removed too: date + therapist + tablet could point back to the person.
          sessions = (
            await tx.session.updateMany({
              where: { patientId },
              data: { patientId: anonymous.id, therapistId: null, therapistVerified: false, guardianId: null }, // and the guardian (spec 112)
            })
          ).count;
        } else {
          sessions = (await tx.session.deleteMany({ where: { patientId } })).count; // events and activities cascade
        }
        await tx.patient.delete({ where: { id: patientId } });

        // The tablets remove it on their next sync (GET /sync/profiles?since=).
        const value = await nextSyncVersion(tx);
        await tx.retiredPatientCode.create({ data: { code: patient.code, syncVersion: value } });

        const { id, respondedAt, status, handledBy, notes } = request;
        await tx.dataRequest.update({ where: { id }, data: { respondedAt, status, handledBy, notes } });
        return { files, sessions };
      },
      { timeout: 60_000 },
    );
  }
}
